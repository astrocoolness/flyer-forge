export function getFormat(id: string): FormatSpec {
  return formats.find((item) => item.id === id) ?? formats[0];
}

export function getTheme(id: string): ThemeSpec {
  return themes.find((item) => item.id === id) ?? themes[0];
}

export function getFontPair(id: string): FontPair {
  return fontPairs.find((item) => item.id === id) ?? fontPairs[0];
}

export function getLayout(id: string): LayoutSpec {
  return layouts.find((item) => item.id === id) ?? layouts[0];
}

export function getStarter(id: string): Starter {
  return starters.find((item) => item.id === id) ?? starters[0];
}

export function catalogBrief(): string {
  return [
    `formats: ${formats.map((item) => `${item.id} (${item.name}, ${item.detail})`).join("; ")}`,
    `layouts: ${layouts.map((item) => `${item.id} (${item.hint})`).join("; ")}`,
    `themes: ${themes.map((item) => `${item.id} (${item.name}, ${item.vibe}, ${item.group})`).join("; ")}`,
    `fontPairs: ${fontPairs.map((item) => `${item.id} (${item.display} + ${item.body})`).join("; ")}`,
    `textures: clean, grain, halftone, rules, speckle, stripes, xerox`,
  ].join("\n");
}

export function centeredLayout(layoutId: string): boolean {
  return layoutId === "stage" || layoutId === "marquee" || layoutId === "poster" || layoutId === "frame";
}
